"""Run one short authored display probe with retained Windows diagnostics.

This tool does not isolate a physical GPU from the desktop. Hardware is opt-in.
"""
import argparse
from datetime import datetime, timedelta, timezone
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import time

BACKENDS = ("software", "direct3d12", "vulkan")
SHADERS = ("off", "sharp", "crt", "smooth", "lcd", "mono", "crt-mask")
MAX_EVENTS = 256
WOW_NAMES = {"wow", "wow-64", "wowclassic", "wowclassic-64", "worldofwarcraft"}


def _utc():
    return datetime.now(timezone.utc).isoformat()


def _hash(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def _frame(path):
    try:
        from compare_frames import read_ppm
    except ImportError:
        from scripts.compare_frames import read_ppm
    width, height, _ = read_ppm(path)
    if width*height > 4_194_304:
        raise ValueError("Probe frame exceeds the display readback limit")
    return {"path": path.name, "size_bytes": path.stat().st_size, "sha256": _hash(path),
            "width": width, "height": height}


def _write(path, value):
    with path.open("x", encoding="utf-8", newline="\n") as stream:
        json.dump(value, stream, indent=2)
        stream.write("\n")
        stream.flush()
        os.fsync(stream.fileno())


def _powershell(script, timeout=4):
    """Read-only, bounded diagnostic query. No interpolation of shell commands."""
    if os.name != "nt":
        return {"available": False, "reason": "Windows telemetry unavailable on this platform"}
    try:
        result = subprocess.run(
            ["powershell.exe", "-NoLogo", "-NoProfile", "-NonInteractive", "-Command", script],
            capture_output=True, text=True, encoding="utf-8", errors="replace",
            timeout=timeout, creationflags=subprocess.CREATE_NO_WINDOW,
        )
        if result.returncode:
            return {"available": False, "reason": "diagnostic query failed", "exit_code": result.returncode,
                    "stderr": result.stderr[-8192:], "stdout": result.stdout[-8192:]}
        value = json.loads(result.stdout)
        return {"available": True, "data": value}
    except (OSError, ValueError, subprocess.TimeoutExpired) as error:
        return {"available": False, "reason": str(error)}


def system_snapshot():
    return _powershell(r"""
$ErrorActionPreference='Stop'
[Console]::OutputEncoding=[System.Text.UTF8Encoding]::new($false)
$gpus=@(Get-CimInstance Win32_VideoController | Select-Object Name,DriverVersion,DriverDate,PNPDeviceID,Status)
$games=@(Get-Process | Where-Object { $_.ProcessName -match '^(WoW|WoW-64|WoWClassic|WoWClassic-64|WorldOfWarcraft)$' } | Select-Object ProcessName,Id,StartTime)
@{gpus=$gpus;games=$games} | ConvertTo-Json -Depth 5 -Compress
""")


def event_snapshot(since, timeout=4):
    # The timestamp is generated by this module, not passed from the shell/user.
    stamp = datetime.fromisoformat(since).astimezone(timezone.utc).isoformat()
    script = r"""
$ErrorActionPreference='Stop'
[Console]::OutputEncoding=[System.Text.UTF8Encoding]::new($false)
$start=[DateTimeOffset]::Parse('__STAMP__').UtcDateTime
$reports=@()
foreach($log in @('System','Application')) {
  $found=@()
  try { $found=@(Get-WinEvent -FilterHashtable @{LogName=$log;StartTime=$start} -MaxEvents 256 -ErrorAction Stop) }
  catch { if($_.FullyQualifiedErrorId -notlike 'NoMatchingEventsFound*') { throw } }
  $rows=@($found | Where-Object {
    ($log -eq 'System' -and $_.ProviderName -match '^(Display|nvlddmkm|Microsoft-Windows-DxgKrnl|amdkmdag|amdwddmg)$') -or
    ($log -eq 'Application' -and $_.Id -in @(1000,1001,1002) -and $_.ProviderName -in @('Application Error','Application Hang','Windows Error Reporting'))
  } | ForEach-Object { @{log=$log;record_id=$_.RecordId;provider=$_.ProviderName;id=$_.Id;level=$_.LevelDisplayName;time=$_.TimeCreated.ToUniversalTime().ToString('o');message=$_.Message} })
  $reports+=@{log=$log;scanned=$found.Count;truncated=($found.Count -ge 256);events=$rows}
}
@{logs=$reports} | ConvertTo-Json -Depth 6 -Compress
""".replace("__STAMP__", stamp)
    return _powershell(script, timeout=max(0.05, timeout))


def _events(report):
    if report.get("available") is not True:
        return []
    return [event for log in report["data"]["logs"] for event in log["events"]]


def graphics_faults(report):
    """Keep raw events; this conservative classification is not root cause."""
    faults = []
    for event in _events(report):
        provider = event["provider"].lower()
        message = event.get("message", "").lower()
        if event["log"] == "System":
            # Driver errors are sufficient to stop this experiment even when the
            # message does not explicitly call the event a reset.
            if provider in ("display", "nvlddmkm", "amdkmdag", "amdwddmg") or (
                    "dxgkrnl" in provider and any(word in message for word in ("reset", "timeout", "hung", "removed"))):
                faults.append(event)
        elif any(word in message for word in ("livekernelevent", "pce-display-probe", "dxgi_error_device", "device lost")):
            faults.append(event)
    return faults


def _complete_events(report):
    if report.get("available") is not True or not isinstance(report.get("data"), dict):
        return False
    logs = report["data"].get("logs")
    return (isinstance(logs, list) and len(logs) == 2 and
            all(isinstance(log, dict) for log in logs) and
            {log.get("log") for log in logs} == {"System", "Application"} and
            all(type(log.get("scanned")) is int and 0 <= log["scanned"] <= MAX_EVENTS and
                log.get("truncated") is False and isinstance(log.get("events"), list) and
                len(log["events"]) <= log["scanned"] for log in logs))


def _wow_active(snapshot):
    if snapshot.get("available") is not True:
        return None
    return any(row["ProcessName"].lower() in WOW_NAMES for row in snapshot["data"]["games"])


def run_probe(executable, output, *, backend="software", shader="off", allow_hardware=False, timeout=8,
              isolated_desktop=False):
    executable, output = Path(executable).resolve(), Path(output).resolve()
    if backend not in BACKENDS or shader not in SHADERS:
        raise ValueError("Unsupported probe backend or shader")
    if isinstance(timeout, bool) or not isinstance(timeout, (int, float)) or not 1 <= timeout <= 15:
        raise ValueError("Probe timeout must be in 1..15 seconds")
    hardware = backend != "software"
    if isolated_desktop and os.name != "nt":
        raise ValueError("--isolated-desktop requires Windows")
    if hardware and not allow_hardware:
        raise ValueError("Physical GPU testing requires --allow-hardware")
    if not hardware and shader != "off":
        raise ValueError("Software SDL probe requires --shader off; GPU shaders need an explicit hardware backend")
    if not executable.is_file() or executable.is_symlink():
        raise ValueError("Probe executable must be an existing ordinary file")
    output.mkdir(parents=True, exist_ok=False)
    receipt = {"schema": 1, "passed": False, "status": "preflight", "backend": backend, "shader": shader,
               "isolated_desktop": isolated_desktop,
               "physical_gpu_requested": hardware, "timeout_seconds": timeout, "started_utc": _utc(),
               "executable": {"path": str(executable), "sha256": _hash(executable)},
               "dlls": [{"name": p.name, "sha256": _hash(p)} for p in sorted(executable.parent.glob("*.dll"))],
               "scope": "One authored hidden display probe; event correlation does not establish root cause"}
    started = time.monotonic()
    journal = (output / "lifecycle.jsonl").open("x", encoding="utf-8", newline="\n", buffering=1)

    def log(kind, **details):
        journal.write(json.dumps({"event": kind, "utc": _utc(), "elapsed_seconds": time.monotonic()-started, **details})+"\n")
        journal.flush()
        os.fsync(journal.fileno())

    process = None
    try:
        log("preflight")
        before_system = system_snapshot()
        before_events = event_snapshot((datetime.now(timezone.utc)-timedelta(seconds=5)).isoformat())
        _write(output/"system-before.json", before_system)
        _write(output/"events-before.json", before_events)
        receipt["preflight_telemetry_available"] = before_system.get("available") is True and _complete_events(before_events)
        active = _wow_active(before_system)
        if hardware and (active is None or not receipt["preflight_telemetry_available"]):
            receipt.update(status="blocked", reason="Hardware probe requires available, untruncated Windows preflight telemetry")
            log("blocked", reason=receipt["reason"])
            return receipt
        if hardware and active:
            receipt.update(status="skipped", reason="World of Warcraft is running; no hardware probe was started")
            log("skipped", reason=receipt["reason"])
            return receipt
        run_since = _utc()
        command = [str(executable), "--backend", backend, "--shader", shader, "--out", str(output/"frame.ppm")]
        receipt["command"] = command
        # This immutable manifest is durable before a render process exists.
        # A killed/frozen wrapper can leave a valid forensic prefix without a
        # final receipt. It must never be mistaken for a completed qualification.
        _write(output/"launch.json", {**receipt, "run_since_utc": run_since,
                                      "status": "launch-intent", "passed": False})
        log("launch-intent", command=command)
        environment = os.environ.copy()
        environment["SDL_AUDIODRIVER"] = "dummy"
        if hardware:
            environment["SDL_GPU_DRIVER"] = backend
            environment.pop("SDL_RENDER_DRIVER", None)
            environment.pop("SDL_VIDEODRIVER", None)
        else:
            environment.update(SDL_VIDEODRIVER="dummy", SDL_RENDER_DRIVER="software")
        with (output/"stdout.log").open("xb") as stdout, (output/"stderr.log").open("xb") as stderr:
            if isolated_desktop:
                try:
                    from hidden_desktop import IsolatedProcess
                except ImportError:
                    from scripts.hidden_desktop import IsolatedProcess
                process = IsolatedProcess(command, stdout=stdout, stderr=stderr, env=environment)
                receipt["desktop_name"] = process.desktop_name
            else:
                process = subprocess.Popen(command, stdout=stdout, stderr=stderr, env=environment,
                                           creationflags=subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0)
            log("started", pid=process.pid)
            receipt["pid"] = process.pid
            deadline = time.monotonic()+timeout
            next_query = time.monotonic()+1
            index = 0
            while process.poll() is None:
                remaining = deadline-time.monotonic()
                if remaining <= 0:
                    receipt.update(status="timeout", reason="Owned display probe exceeded its wall deadline")
                    log("timeout")
                    process.kill()
                    break
                if hardware and time.monotonic() >= next_query:
                    observed = event_snapshot(run_since, timeout=min(2, remaining))
                    _write(output/f"events-during-{index:02d}.json", observed)
                    index += 1
                    faults = graphics_faults(observed)
                    if faults:
                        receipt.update(status="graphics-event", reason="A new graphics error was recorded during the probe")
                        log("graphics-event", events=faults)
                        process.kill()
                        break
                    if not _complete_events(observed):
                        receipt.update(status="telemetry-lost", reason="Graphics event monitoring became unavailable or truncated")
                        log("telemetry-lost")
                        process.kill()
                        break
                    next_query = time.monotonic()+1
                log("running", pid=process.pid)
                try:
                    process.wait(timeout=min(0.25, max(0.01, deadline-time.monotonic())))
                except subprocess.TimeoutExpired:
                    pass
            receipt["exit_code"] = process.wait(timeout=3)
            log("exited", exit_code=receipt["exit_code"])
        # Allow promptly logged WER/display events to arrive without running a
        # second probe or submitting additional rendering work.
        time.sleep(2)
        after_events = event_snapshot(run_since)
        after_system = system_snapshot()
        _write(output/"events-after.json", after_events)
        _write(output/"system-after.json", after_system)
        faults = graphics_faults(after_events)
        receipt["graphics_events"] = faults
        receipt["post_telemetry_available"] = after_system.get("available") is True and _complete_events(after_events)
        frame = output/"frame.ppm"
        if frame.is_file():
            receipt["frame"] = _frame(frame)
        if receipt["status"] == "preflight":
            if faults:
                receipt.update(status="graphics-event", reason="A new graphics error was recorded around the probe")
            elif hardware and not receipt["post_telemetry_available"]:
                receipt.update(status="telemetry-lost", reason="Post-probe graphics diagnostics unavailable or truncated")
            elif receipt["exit_code"] != 0:
                receipt.update(status="probe-failed", reason="Probe exited unsuccessfully; inspect stdout/stderr")
            elif "frame" not in receipt:
                receipt.update(status="probe-failed", reason="Probe did not produce its required frame")
            elif _hash(executable) != receipt["executable"]["sha256"]:
                receipt.update(status="probe-failed", reason="Probe executable changed during the run")
            elif [{"name": p.name, "sha256": _hash(p)} for p in sorted(executable.parent.glob("*.dll"))] != receipt["dlls"]:
                receipt.update(status="probe-failed", reason="Adjacent runtime DLLs changed during the run")
            else:
                receipt.update(passed=True, status="passed")
        return receipt
    except Exception as error:
        receipt.update(status="error", reason=f"{type(error).__name__}: {error}")
        log("error", reason=receipt["reason"])
        return receipt
    finally:
        try:
            if process is not None and process.poll() is None:
                process.kill()
                process.wait(timeout=3)
                log("cleanup-killed", pid=process.pid)
            receipt["process_closed"] = process is None or process.poll() is not None
        except (OSError, subprocess.TimeoutExpired) as error:
            receipt.update(passed=False, status="cleanup-failed", process_closed=False,
                           cleanup_error=f"{type(error).__name__}: {error}")
            log("cleanup-failed", reason=receipt["cleanup_error"])
        if isolated_desktop and process is not None:
            try:
                process.close()
                receipt["desktop_closed"] = True
            except OSError as error:
                receipt.update(passed=False, status="cleanup-failed", desktop_closed=False,
                               desktop_cleanup_error=str(error))
                log("desktop-cleanup-failed", reason=str(error))
        receipt["finished_utc"] = _utc()
        receipt["elapsed_seconds"] = time.monotonic()-started
        log("finished", status=receipt["status"], process_closed=receipt["process_closed"])
        _write(output/"receipt.json", receipt)
        journal.close()


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("executable", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--backend", choices=BACKENDS, default="software")
    parser.add_argument("--shader", choices=SHADERS, default="off")
    parser.add_argument("--allow-hardware", action="store_true")
    parser.add_argument("--isolated-desktop", action="store_true",
                        help="Windows only: create a unique private desktop without switching the input desktop")
    parser.add_argument("--timeout", type=float, default=8)
    args = parser.parse_args(argv)
    try:
        result = run_probe(args.executable, args.out, backend=args.backend, shader=args.shader,
                           allow_hardware=args.allow_hardware, timeout=args.timeout,
                           isolated_desktop=args.isolated_desktop)
    except (OSError, ValueError) as error:
        parser.error(str(error))
    print(json.dumps(result, indent=2))
    return 0 if result["passed"] else 1


if __name__ == "__main__":
    sys.exit(main())
