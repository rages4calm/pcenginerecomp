"""Compile the authored SDL GPU fragment shader into the public C++ header."""
import argparse
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'runtime/shaders/display.hlsl'
HEADER = ROOT / 'runtime/include/pce/display_shader_data.hpp'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dxc', default='dxc')
    parser.add_argument('--check', action='store_true', help='Compare without writing')
    args = parser.parse_args()
    header = [
        '#pragma once',
        '// Generated by scripts/build_display_shader.py from runtime/shaders/display.hlsl.',
        'namespace pce::display_shader {',
    ]
    with tempfile.TemporaryDirectory() as directory:
        for name, options in (
            ('spirv', ['-spirv', '-fspv-target-env=vulkan1.0', '-D', 'PCE_SPIRV=1']),
            ('dxil', []),
        ):
            output = Path(directory) / name
            subprocess.run([
                args.dxc, '-T', 'ps_6_0', '-E', 'main', '-O3', '-Qstrip_debug',
                *options, '-Fo', str(output), str(SOURCE),
            ], check=True)
            code = output.read_bytes()
            header.append(f'alignas(4) inline constexpr unsigned char {name}[] = {{')
            header.extend('    ' + ', '.join(f'0x{x:02x}' for x in code[i:i+16]) + ','
                          for i in range(0, len(code), 16))
            header.append('};')
    header.extend(['}', ''])
    content = '\n'.join(header).encode('utf-8')
    if args.check:
        if HEADER.read_bytes() != content:
            raise SystemExit('Display shader header differs')
    else:
        HEADER.write_bytes(content)


if __name__ == '__main__':
    main()
